"""Run a step of the ranking study on the development projects (docs/adr/0013, 0014).

uv run python -m benchmarks.study baseline          # latest failure and testhunch 0.2.0
uv run python -m benchmarks.study step-1 --jobs 2   # fewer projects at once, less memory

Held-out projects are not accepted: they are replayed once, after the study stops (ADR 0013).
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
from collections.abc import Sequence
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path
from typing import Any

from benchmarks.split import HARNESS_DEVELOPMENT, RTPTORRENT_DEVELOPMENT
from benchmarks.study.engine import PRIMARY, compare
from benchmarks.study.metrics import BUDGETS, time_to_catch
from benchmarks.study.projects import AUTHORS_SCHEDULE, CACHE, STEPS, Step, run
from testhunch import __version__
from testhunch.gitinfo import GitError, rev_parse

DEFAULT_OUT = CACHE / "study"
CATCH_SHARES = (0.9, 0.95)
SECONDARY = ("apfdc", "apfd", *(f"time_{f}" for f in BUDGETS), *(f"tests_{f}" for f in BUDGETS))


def _mean(result: dict[str, Any], ranking: str, measure: str, kind: str = "job") -> float | None:
    value = result["rankings"][ranking]["means"].get(kind, {}).get(measure, {}).get("mean")
    return float(value) if isinstance(value, (int, float)) else None


def _cell(value: float | None, signed: bool = False) -> str:
    if value is None:
        return "-"
    return f"{value:+.3f}" if signed else f"{value:.3f}"


def summary(results: Sequence[dict[str, Any]], name: str, step: Step) -> str:
    current = step.current.name
    candidates = [ranking.name for ranking in step.candidates]
    references = [ranking.name for ranking in step.references]
    names = [current, *candidates, *references]
    rtptorrent = sorted(
        (r for r in results if r["source"] == "rtptorrent"), key=lambda r: r["project"].lower()
    )
    primary = {
        ranking: {
            r["project"]: value
            for r in rtptorrent
            if (value := _mean(r, ranking, PRIMARY)) is not None
        }
        for ranking in names
    }
    lines = [
        f"# Ranking study: {name}",
        "",
        "Generated by `python -m benchmarks.study`; method in docs/adr/0014, development projects "
        "only (docs/adr/0013). Primary measure: APFDc with a job's failures as one fault, averaged "
        "per project over its failing jobs ranked from a non-empty history, then over the "
        f"{len(rtptorrent)} RTPTorrent projects. A candidate beats the current version when the "
        "95% bootstrap interval of the mean difference is above 0, the mean difference is at least "
        "0.005, and it scores higher on at least 6 of 10 projects.",
        "",
        "| Ranking | Role | Primary | Difference | 95% interval | Higher on | Beats current |",
        "|---|---|---:|---:|---|---:|---|",
    ]
    complete = bool(rtptorrent) and all(len(primary[r]) == len(rtptorrent) for r in names)
    verdicts: dict[str, dict[str, Any]] = {}
    for ranking in names:
        role = "current" if ranking == current else "candidate"
        role = "reference" if ranking in references else role
        mean = statistics.fmean(primary[ranking].values()) if primary[ranking] else None
        if ranking == current or not complete:
            lines.append(f"| {ranking} | {role} | {_cell(mean)} | | | | |")
            continue
        verdict = verdicts[ranking] = compare(primary[current], primary[ranking])
        low, high = verdict["interval"]
        lines.append(
            f"| {ranking} | {role} | {_cell(mean)} | {verdict['mean_difference']:+.3f} | "
            f"[{low:+.3f}, {high:+.3f}] | {verdict['higher_on']} of {verdict['projects']} | "
            f"{'yes' if verdict['beats'] else 'no'} |"
        )
    winners = [c for c in candidates if verdicts.get(c, {}).get("beats")]
    lines.append("")
    if not complete:
        lines.append("Some projects are missing: no verdict.")
    elif winners:
        kept = max(winners, key=lambda c: verdicts[c]["mean_difference"])
        lines.append(f"**Kept: {kept}**, the candidate that beats {current} by the most.")
    elif candidates:
        lines.append(f"**No candidate beats {current}: the study stops here.**")

    short = [r["project"].split("@", 1)[1] for r in rtptorrent]
    trials = [
        str(r["rankings"][current]["means"].get("job", {}).get(PRIMARY, {}).get("trials", 0))
        for r in rtptorrent
    ]
    lines += [
        "",
        "## Primary measure per RTPTorrent project",
        "",
        "| Ranking | " + " | ".join(short) + " |",
        "|---|" + "---:|" * len(short),
        "| *failing jobs* | " + " | ".join(trials) + " |",
    ]
    for ranking in names:
        cells = [_cell(primary[ranking].get(r["project"])) for r in rtptorrent]
        lines.append(f"| {ranking} | " + " | ".join(cells) + " |")

    lines += [
        "",
        "## Secondary measures, mean of the RTPTorrent per-project means",
        "",
        "| Ranking | " + " | ".join(SECONDARY) + " |",
        "|---|" + "---:|" * len(SECONDARY),
    ]
    for ranking in names:
        cells = []
        for measure in SECONDARY:
            values = [v for r in rtptorrent if (v := _mean(r, ranking, measure)) is not None]
            cells.append(_cell(statistics.fmean(values) if values else None))
        lines.append(f"| {ranking} | " + " | ".join(cells) + " |")

    lines += [
        "",
        "## Share of the test time needed to turn failing jobs red",
        "",
        "Per project, the smallest share of each failing job's test time within which 90% (or 95%) "
        "of its failing jobs turn red, running tests in the ranking's order; then the mean over "
        "the RTPTorrent projects.",
        "",
        "| Ranking | " + " | ".join(f"{s:.0%} caught" for s in CATCH_SHARES) + " |",
        "|---|" + "---:|" * len(CATCH_SHARES),
    ]
    for ranking in names:
        red_at = [
            [v for v in r["rankings"][ranking]["per_trial"].get("red_at", []) if v is not None]
            for r in rtptorrent
        ]
        cells = [
            _cell(
                statistics.fmean(time_to_catch(red, share) for red in red_at)
                if red_at and all(red_at)
                else None
            )
            for share in CATCH_SHARES
        ]
        lines.append(f"| {ranking} | " + " | ".join(cells) + " |")

    authors = [r for r in rtptorrent if r.get("authors_schedule", {}).get("jobs")]
    if authors:
        shown = [AUTHORS_SCHEDULE, current, *references]
        lines += [
            "",
            f"## Mean APFD on the jobs the authors' {AUTHORS_SCHEDULE} schedules cover",
            "",
            "| Project | Jobs | " + " | ".join(shown) + " |",
            "|---|---:|" + "---:|" * len(shown),
        ]
        for result in authors:
            check = result["authors_schedule"]
            cells = [_cell(check["mean_apfd"].get(column)) for column in shown]
            lines.append(f"| {result['project']} | {check['jobs']} | " + " | ".join(cells) + " |")

    harness = sorted((r for r in results if r["source"] == "harness"), key=lambda r: r["project"])
    columns = [(r, kind) for r in harness for kind in sorted(r["rankings"][current]["means"])]
    if columns:
        headers = [
            f"{r['project']} {kind}s ({r['rankings'][current]['means'][kind][PRIMARY]['trials']})"
            for r, kind in columns
        ]
        lines += [
            "",
            "## Harness development projects: primary measure (reported, not deciding)",
            "",
            "| Ranking | " + " | ".join(headers) + " |",
            "|---|" + "---:|" * len(columns),
        ]
        for ranking in names:
            cells = [_cell(_mean(r, ranking, PRIMARY, kind)) for r, kind in columns]
            lines.append(f"| {ranking} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m benchmarks.study")
    parser.add_argument("step", choices=sorted(STEPS))
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--jobs", type=int, default=4, help="projects replayed at once")
    parser.add_argument(
        "--projects",
        nargs="+",
        choices=[*RTPTORRENT_DEVELOPMENT, *HARNESS_DEVELOPMENT],
        help="a subset of the development projects",
    )
    args = parser.parse_args(argv)
    chosen = args.projects or [*RTPTORRENT_DEVELOPMENT, *HARNESS_DEVELOPMENT]
    tasks = [
        ("rtptorrent" if project in RTPTORRENT_DEVELOPMENT else "harness", project, args.step)
        for project in chosen
    ]
    out = args.out / args.step
    out.mkdir(parents=True, exist_ok=True)
    commit = _commit()
    with ProcessPoolExecutor(max_workers=args.jobs) as pool:
        for result in pool.map(run, tasks):
            result["testhunch"] = {"version": __version__, "commit": commit}
            slug = result["project"].replace("/", "@")
            (out / f"{slug}.json").write_text(json.dumps(result) + "\n", encoding="utf-8")
            sys.stdout.write(f"{result['project']}: {result['counts']}\n")
    everything = [
        json.loads(path.read_text(encoding="utf-8")) for path in sorted(out.glob("*.json"))
    ]
    page = summary(everything, args.step, STEPS[args.step])
    (out / "README.md").write_bytes(page.encode("utf-8"))
    return 0


def _commit() -> str | None:
    try:
        return rev_parse("HEAD")
    except GitError:
        return None


if __name__ == "__main__":
    sys.exit(main())
