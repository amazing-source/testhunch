"""Run the ranking study on the development projects (docs/adr/0013, 0014).

uv run python -m benchmarks.study baseline            # latest failure and testhunch 0.2.0
uv run python -m benchmarks.study baseline --jobs 2   # fewer projects at once, less memory

Held-out projects are not accepted: they are replayed once, after the study stops (ADR 0013).
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
from collections.abc import Sequence
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path
from typing import Any

from benchmarks.split import HARNESS_DEVELOPMENT, RTPTORRENT_DEVELOPMENT
from benchmarks.study.engine import PRIMARY, compare
from benchmarks.study.metrics import BUDGETS
from benchmarks.study.projects import AUTHORS_SCHEDULE, CACHE, run
from testhunch import __version__
from testhunch.gitinfo import GitError, rev_parse

DEFAULT_OUT = CACHE / "study"


def summary(results: Sequence[dict[str, Any]], step: str) -> str:
    names = list(results[0]["rankings"]) if results else []
    lines = [
        f"# Ranking study: {step}",
        "",
        "Generated by `python -m benchmarks.study`; method in docs/adr/0014, development projects "
        "only (docs/adr/0013). Primary measure: APFDc with a job's failures as one fault, over "
        "the failing jobs ranked from a non-empty history.",
        "",
        "## RTPTorrent development projects",
        "",
        "| Project | Failing jobs | " + " | ".join(names) + " |",
        "|---|---:|" + "---:|" * len(names),
    ]
    rtptorrent = [r for r in results if r["source"] == "rtptorrent"]
    primary: dict[str, dict[str, float]] = {name: {} for name in names}
    for result in rtptorrent:
        cells = []
        trials = 0
        for name in names:
            measure = result["rankings"][name]["means"].get("job", {}).get(PRIMARY)
            if measure is None or measure["mean"] is None:
                cells.append("-")
                continue
            primary[name][result["project"]] = measure["mean"]
            trials = measure["trials"]
            cells.append(f"{measure['mean']:.3f}")
        lines.append(f"| {result['project']} | {trials} | " + " | ".join(cells) + " |")

    lines += ["", "Secondary measures, mean of the per-project means:", ""]
    measures = ["apfdc", "apfd", *(f"time_{f}" for f in BUDGETS), *(f"tests_{f}" for f in BUDGETS)]
    lines += ["| Measure | " + " | ".join(names) + " |", "|---|" + "---:|" * len(names)]
    for measure in measures:
        cells = []
        for name in names:
            values = [
                r["rankings"][name]["means"]["job"][measure]["mean"]
                for r in rtptorrent
                if r["rankings"][name]["means"].get("job", {}).get(measure, {}).get("mean")
                is not None
            ]
            cells.append(f"{statistics.fmean(values):.3f}" if values else "-")
        lines.append(f"| {measure} | " + " | ".join(cells) + " |")

    if len(names) > 1 and all(len(primary[name]) == len(rtptorrent) for name in names):
        reference = names[0]
        lines += [
            "",
            f"Against {reference} (ADR 0014: interval above 0 and higher on 6 of 10):",
            "",
        ]
        for name in names[1:]:
            verdict = compare(primary[reference], primary[name])
            low, high = verdict["interval"]
            lines.append(
                f"- {name}: mean difference {verdict['mean_difference']:+.3f}, 95% interval "
                f"[{low:+.3f}, {high:+.3f}], higher on {verdict['higher_on']} of "
                f"{verdict['projects']} projects: "
                f"{'beats' if verdict['beats'] else 'does not beat'} {reference}."
            )

    authors = [r for r in rtptorrent if r.get("authors_schedule", {}).get("jobs")]
    if authors:
        lines += [
            "",
            f"Mean APFD on the jobs the authors' {AUTHORS_SCHEDULE} schedules cover, to check the "
            "latest failure against their implementation:",
            "",
            "| Project | Jobs | " + " | ".join([AUTHORS_SCHEDULE, *names]) + " |",
            "|---|---:|" + "---:|" * (len(names) + 1),
        ]
        for result in authors:
            check = result["authors_schedule"]
            cells = [
                f"{check['mean_apfd'][n]:.3f}" if check["mean_apfd"][n] is not None else "-"
                for n in [AUTHORS_SCHEDULE, *names]
            ]
            lines.append(f"| {result['project']} | {check['jobs']} | " + " | ".join(cells) + " |")

    harness = [r for r in results if r["source"] == "harness"]
    if harness:
        lines += [
            "",
            "## Harness development projects (reported, not deciding)",
            "",
            "| Project | Kind | Trials | " + " | ".join(names) + " |",
            "|---|---|---:|" + "---:|" * len(names),
        ]
        for result in harness:
            for kind in sorted(result["rankings"][names[0]]["means"]):
                cells = []
                trials = 0
                for name in names:
                    measure = result["rankings"][name]["means"][kind][PRIMARY]
                    trials = measure["trials"]
                    cells.append(f"{measure['mean']:.3f}" if measure["mean"] is not None else "-")
                lines.append(
                    f"| {result['project']} | {kind} | {trials} | " + " | ".join(cells) + " |"
                )
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m benchmarks.study")
    parser.add_argument("step", choices=("baseline",))
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--jobs", type=int, default=4, help="projects replayed at once")
    parser.add_argument(
        "--projects",
        nargs="+",
        choices=[*RTPTORRENT_DEVELOPMENT, *HARNESS_DEVELOPMENT],
        help="a subset of the development projects",
    )
    args = parser.parse_args(argv)
    chosen = args.projects or [*RTPTORRENT_DEVELOPMENT, *HARNESS_DEVELOPMENT]
    tasks = [
        ("rtptorrent" if project in RTPTORRENT_DEVELOPMENT else "harness", project, args.step)
        for project in chosen
    ]
    out = args.out / args.step
    out.mkdir(parents=True, exist_ok=True)
    commit = _commit()
    with ProcessPoolExecutor(max_workers=args.jobs) as pool:
        for result in pool.map(run, tasks):
            result["testhunch"] = {"version": __version__, "commit": commit}
            slug = result["project"].replace("/", "@")
            (out / f"{slug}.json").write_text(json.dumps(result) + "\n", encoding="utf-8")
            sys.stdout.write(f"{result['project']}: {result['counts']}\n")
    everything = [
        json.loads(path.read_text(encoding="utf-8")) for path in sorted(out.glob("*.json"))
    ]
    (out / "README.md").write_text(summary(everything, args.step), encoding="utf-8")
    return 0


def _commit() -> str | None:
    try:
        return rev_parse("HEAD")
    except GitError:
        return None


if __name__ == "__main__":
    sys.exit(main())
