"""Run a step of the ranking study on the development projects (docs/adr/0013, 0014).

uv run python -m benchmarks.study baseline          # latest failure and testhunch 0.2.0
uv run python -m benchmarks.study step-1 --jobs 2   # fewer projects at once, less memory

uv run python -m benchmarks.study held-out --held-out  # once, after the study stopped (ADR 0013)
"""

from __future__ import annotations

import argparse
import json
import math
import statistics
import sys
from collections.abc import Sequence
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path
from typing import Any

from benchmarks.heldout import NotFrozen, record_peek
from benchmarks.split import (
    HARNESS_DEVELOPMENT,
    HARNESS_HELD_OUT,
    RTPTORRENT_DEVELOPMENT,
    RTPTORRENT_HELD_OUT,
)
from benchmarks.study.engine import MIN_DIFFERENCE, PRIMARY, compare
from benchmarks.study.metrics import BUDGETS, time_to_catch
from benchmarks.study.projects import AUTHORS_SCHEDULE, CACHE, HELD_OUT_STEP, STEPS, Step, run
from testhunch import __version__
from testhunch.gitinfo import GitError, rev_parse

DEFAULT_OUT = CACHE / "study"
CATCH_SHARES = (0.9, 0.95)
SECONDARY = ("apfdc", "apfd", *(f"time_{f}" for f in BUDGETS), *(f"tests_{f}" for f in BUDGETS))


def _mean(result: dict[str, Any], ranking: str, measure: str, kind: str = "job") -> float | None:
    value = result["rankings"][ranking]["means"].get(kind, {}).get(measure, {}).get("mean")
    return float(value) if isinstance(value, (int, float)) else None


def _cell(value: float | None, signed: bool = False) -> str:
    if value is None:
        return "-"
    return f"{value:+.3f}" if signed else f"{value:.3f}"


def summary(results: Sequence[dict[str, Any]], name: str, step: Step) -> str:
    current = step.current.name
    candidates = [ranking.name for ranking in step.candidates]
    references = [ranking.name for ranking in step.references]
    names = [current, *candidates, *references]
    rtptorrent = sorted(
        (r for r in results if r["source"] == "rtptorrent"), key=lambda r: r["project"].lower()
    )
    primary = {
        ranking: {
            r["project"]: value
            for r in rtptorrent
            if (value := _mean(r, ranking, PRIMARY)) is not None
        }
        for ranking in names
    }
    # The page must name the projects it was run on: this one was published claiming "development
    # projects only" while listing the ten held out for it.
    projects = "held-out projects" if name == HELD_OUT_STEP else "development projects only"
    wins = math.ceil(0.6 * len(rtptorrent))
    lines = [
        f"# Ranking study: {name}",
        "",
        f"Generated by `python -m benchmarks.study`; method in docs/adr/0014, {projects} "
        "(docs/adr/0013). Primary measure: APFDc with a job's failures as one fault, averaged "
        "per project over its failing jobs ranked from a non-empty history, then over the "
        f"{len(rtptorrent)} RTPTorrent projects. A candidate beats the current version when the "
        "95% bootstrap interval of the mean difference is above 0, the mean difference is at least "
        f"{MIN_DIFFERENCE}, and it scores higher on at least {wins} of {len(rtptorrent)} projects.",
        "",
        "| Ranking | Role | Primary | Difference | 95% interval | Higher on | Beats current |",
        "|---|---|---:|---:|---|---:|---|",
    ]
    complete = bool(rtptorrent) and all(len(primary[r]) == len(rtptorrent) for r in names)
    verdicts: dict[str, dict[str, Any]] = {}
    for ranking in names:
        role = "current" if ranking == current else "candidate"
        role = "reference" if ranking in references else role
        mean = statistics.fmean(primary[ranking].values()) if primary[ranking] else None
        if ranking == current or not complete:
            lines.append(f"| {ranking} | {role} | {_cell(mean)} | | | | |")
            continue
        verdict = verdicts[ranking] = compare(primary[current], primary[ranking])
        low, high = verdict["interval"]
        lines.append(
            f"| {ranking} | {role} | {_cell(mean)} | {verdict['mean_difference']:+.3f} | "
            f"[{low:+.3f}, {high:+.3f}] | {verdict['higher_on']} of {verdict['projects']} | "
            f"{'yes' if verdict['beats'] else 'no'} |"
        )
    winners = [c for c in candidates if verdicts.get(c, {}).get("beats")]
    lines.append("")
    if not complete:
        lines.append("Some projects are missing: no verdict.")
    elif name == HELD_OUT_STEP:
        lines.append(
            "Held-out projects, replayed once with the versions the study kept (ADR 0013): "
            + (
                ", ".join(f"**{c} beats {current}**" for c in winners)
                if winners
                else f"**no kept version beats {current}**"
            )
            + "."
        )
    elif winners:
        kept = max(winners, key=lambda c: verdicts[c]["mean_difference"])
        lines.append(f"**Kept: {kept}**, the candidate that beats {current} by the most.")
    elif candidates:
        lines.append(f"**No candidate beats {current}: the study stops here.**")

    short = [r["project"].split("@", 1)[1] for r in rtptorrent]
    trials = [
        str(r["rankings"][current]["means"].get("job", {}).get(PRIMARY, {}).get("trials", 0))
        for r in rtptorrent
    ]
    lines += [
        "",
        "## Primary measure per RTPTorrent project",
        "",
        "The row of counts is the failing jobs the primary measure covers, not every failing job: "
        "a job with a test whose duration is unknown has no APFDc, and is left out of it.",
        "",
        "| Ranking | " + " | ".join(short) + " |",
        "|---|" + "---:|" * len(short),
        "| *jobs in the primary* | " + " | ".join(trials) + " |",
    ]
    for ranking in names:
        cells = [_cell(primary[ranking].get(r["project"])) for r in rtptorrent]
        lines.append(f"| {ranking} | " + " | ".join(cells) + " |")

    lines += [
        "",
        "## Secondary measures, mean of the RTPTorrent per-project means",
        "",
        "| Ranking | " + " | ".join(SECONDARY) + " |",
        "|---|" + "---:|" * len(SECONDARY),
    ]
    for ranking in names:
        cells = []
        for measure in SECONDARY:
            values = [v for r in rtptorrent if (v := _mean(r, ranking, measure)) is not None]
            cells.append(_cell(statistics.fmean(values) if values else None))
        lines.append(f"| {ranking} | " + " | ".join(cells) + " |")

    catch = []
    for ranking in names:
        red_at = [
            [v for v in r["rankings"][ranking]["per_trial"].get("red_at", []) if v is not None]
            for r in rtptorrent
        ]
        cells = [
            _cell(
                statistics.fmean(time_to_catch(red, share) for red in red_at)
                if red_at and all(red_at)
                else None
            )
            for share in CATCH_SHARES
        ]
        catch.append((ranking, cells))
    best = [
        [
            v
            for v, kind in zip(r["trials"]["best_red_at"], r["trials"]["kinds"], strict=True)
            if v is not None and kind == "job"
        ]
        for r in rtptorrent
        if "best_red_at" in r["trials"]
    ]
    if best and len(best) == len(rtptorrent) and all(best):
        catch.append(
            (
                "*best order in hindsight*",
                [
                    _cell(statistics.fmean(time_to_catch(red, share) for red in best))
                    for share in CATCH_SHARES
                ],
            )
        )
    # Results stored before `red_at` was kept per trial have nothing to fill this with. A table of
    # dashes says less than no table, so the section only appears once something fills it.
    if any(cell != "-" for _, cells in catch for cell in cells):
        lines += [
            "",
            "## Share of the test time needed to turn failing jobs red",
            "",
            "Per project, the smallest share of each failing job's test time within which 90% (or "
            "95%) of its failing jobs turn red, running tests in the ranking's order; then the "
            "mean over the RTPTorrent projects.",
            "",
            "| Ranking | " + " | ".join(f"{s:.0%} caught" for s in CATCH_SHARES) + " |",
            "|---|" + "---:|" * len(CATCH_SHARES),
            *(f"| {ranking} | " + " | ".join(cells) + " |" for ranking, cells in catch),
        ]
    lines += _first_failure_table(rtptorrent, names)

    authors = [r for r in rtptorrent if r.get("authors_schedule", {}).get("jobs")]
    if authors:
        shown = [AUTHORS_SCHEDULE, current, *references]
        lines += [
            "",
            f"## Mean APFD on the jobs the authors' {AUTHORS_SCHEDULE} schedules cover",
            "",
            "| Project | Jobs | " + " | ".join(shown) + " |",
            "|---|---:|" + "---:|" * len(shown),
        ]
        for result in authors:
            check = result["authors_schedule"]
            cells = [_cell(check["mean_apfd"].get(column)) for column in shown]
            lines.append(f"| {result['project']} | {check['jobs']} | " + " | ".join(cells) + " |")

    harness = sorted((r for r in results if r["source"] == "harness"), key=lambda r: r["project"])
    columns = [(r, kind) for r in harness for kind in sorted(r["rankings"][current]["means"])]
    if columns:
        headers = [
            f"{r['project']} {kind}s ({r['rankings'][current]['means'][kind][PRIMARY]['trials']})"
            for r, kind in columns
        ]
        lines += [
            "",
            f"## Harness {'held-out' if name == HELD_OUT_STEP else 'development'} projects: "
            "primary measure (reported, not deciding)",
            "",
            "| Ranking | " + " | ".join(headers) + " |",
            "|---|" + "---:|" * len(columns),
        ]
        for ranking in names:
            cells = [_cell(_mean(r, ranking, PRIMARY, kind)) for r, kind in columns]
            lines.append(f"| {ranking} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def _first_failure_table(rtptorrent: Sequence[dict[str, Any]], names: Sequence[str]) -> list[str]:
    """The guardrail of ADR 0018: where the first failing test sits, on each slice.

    A ranking must not be worse than random at finding a test that has never failed. Reported
    beside the main measure and never merged into it: the jobs whose history speaks would
    otherwise drown the ones whose history says nothing.
    """
    if not rtptorrent or not all("first_failure" in r["trials"] for r in rtptorrent):
        return []
    slices = {"had failed before": False, "had never failed before": True}
    lines = [
        "",
        "## Position of the first failing test, by slice (docs/adr/0018)",
        "",
        "Guardrail, not a measure to maximise: **lower is better**, and a ranking must not be "
        "worse than random where the history says nothing. Mean over the jobs of each slice.",
        "",
        "| Ranking | "
        + " | ".join(f"{name} ({n})" for name, n in _slice_counts(rtptorrent))
        + " |",
        "|---|" + "---:|" * len(slices),
    ]
    for ranking in names:
        cells = []
        for fresh in slices.values():
            values = [
                value
                for result in rtptorrent
                for value, kind, first in zip(
                    result["rankings"][ranking]["per_trial"].get("position", []),
                    result["trials"]["kinds"],
                    result["trials"]["first_failure"],
                    strict=True,
                )
                if value is not None and kind == "job" and first == fresh
            ]
            cells.append(_cell(statistics.fmean(values) if values else None))
        lines.append(f"| {ranking} | " + " | ".join(cells) + " |")
    return lines


def _slice_counts(rtptorrent: Sequence[dict[str, Any]]) -> list[tuple[str, int]]:
    jobs = [
        first
        for result in rtptorrent
        for first, kind in zip(
            result["trials"]["first_failure"], result["trials"]["kinds"], strict=True
        )
        if kind == "job"
    ]
    # `is False` and `is True`, not truthiness: a job whose failing tests the ranking had never
    # seen is None, and belongs to neither slice. Counting it as "had failed before" put 80 jobs
    # of the development projects in the slice they are the opposite of (docs/adr/0018).
    return [
        ("had failed before", sum(1 for first in jobs if first is False)),
        ("had never failed before", sum(1 for first in jobs if first is True)),
    ]


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m benchmarks.study")
    parser.add_argument("step", choices=sorted(STEPS))
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--jobs", type=int, default=4, help="projects replayed at once")
    parser.add_argument(
        "--projects",
        nargs="+",
        choices=[
            *RTPTORRENT_DEVELOPMENT,
            *HARNESS_DEVELOPMENT,
            *RTPTORRENT_HELD_OUT,
            *HARNESS_HELD_OUT,
        ],
        help="a subset of the step's projects",
    )
    parser.add_argument(
        "--held-out",
        action="store_true",
        help=f"required by the {HELD_OUT_STEP} step, the only one that replays held-out projects",
    )
    parser.add_argument(
        "--from-cache",
        action="store_true",
        help="rebuild the page from the per-project results already under --out, replaying "
        "nothing. No replay produces no number, so there is no look to record (docs/adr/0016): "
        "this rewrites prose over figures that are already frozen and published",
    )
    args = parser.parse_args(argv)
    if (args.step == HELD_OUT_STEP) != args.held_out:
        parser.error(f"--held-out goes with the {HELD_OUT_STEP} step, and only with it (ADR 0013)")
    rtptorrent = RTPTORRENT_HELD_OUT if args.held_out else RTPTORRENT_DEVELOPMENT
    harness = HARNESS_HELD_OUT if args.held_out else HARNESS_DEVELOPMENT
    chosen = args.projects or [*rtptorrent, *harness]
    wrong = [project for project in chosen if project not in (*rtptorrent, *harness)]
    if wrong:
        parser.error(f"not projects of the {args.step} step: {', '.join(wrong)}")
    out = args.out / args.step
    if args.from_cache:
        if not sorted(out.glob("*.json")):
            parser.error(f"no stored results in {out} to rebuild the page from")
    else:
        if args.held_out:
            # Written before the replay, from a frozen commit, so the look cannot be hidden
            # (ADR 0016).
            try:
                record_peek(
                    f"benchmarks.study {args.step}",
                    chosen,
                    ", ".join(ranking.name for ranking in STEPS[args.step].rankings()),
                    __version__,
                )
            except NotFrozen as exc:
                parser.error(str(exc))
        tasks = [
            ("rtptorrent" if project in rtptorrent else "harness", project, args.step)
            for project in chosen
        ]
        out.mkdir(parents=True, exist_ok=True)
        commit = _commit()
        with ProcessPoolExecutor(max_workers=args.jobs) as pool:
            for result in pool.map(run, tasks):
                result["testhunch"] = {"version": __version__, "commit": commit}
                slug = result["project"].replace("/", "@")
                (out / f"{slug}.json").write_text(json.dumps(result) + "\n", encoding="utf-8")
                sys.stdout.write(f"{result['project']}: {result['counts']}\n")
    everything = [
        json.loads(path.read_text(encoding="utf-8")) for path in sorted(out.glob("*.json"))
    ]
    page = summary(everything, args.step, STEPS[args.step])
    (out / "README.md").write_bytes(page.encode("utf-8"))
    return 0


def _commit() -> str | None:
    try:
        return rev_parse("HEAD")
    except GitError:
        return None


if __name__ == "__main__":
    sys.exit(main())
