"""One page over every project's RTPTorrent results (docs/adr/0010)."""

from __future__ import annotations

from collections.abc import Sequence
from typing import Any

from benchmarks.rtptorrent.data import STRATEGIES

SCHEDULES = ("testhunch", *STRATEGIES)


def summary(results: Sequence[dict[str, Any]]) -> str:
    results = sorted(results, key=lambda result: result["project"].lower())
    fractions = [point["fraction"] for point in results[0]["shadow"]] if results else []
    budgets = " / ".join(f"{fraction:.0%}" for fraction in fractions)
    lines = [
        "# RTPTorrent results",
        "",
        "Generated by `python -m benchmarks.rtptorrent`; method in docs/adr/0010. One page per "
        "project next to this one. Results are per test class, from Travis CI builds of Java "
        "projects, without retries.",
        "",
        "## What running a share of the known test classes would have kept",
        "",
        "Per change: failing jobs still caught, where a job is caught when at least one of its "
        "failing classes runs. Per test: failing classes that run. Classes the ranking does not "
        "know always run, so more than the budget runs.",
        "",
        f"| Project | Jobs | Failing | Failing jobs caught at {budgets} "
        f"| Failing classes caught at {budgets} | Test time run at {budgets} |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    pairs = (
        ("caught_runs", "failing_runs"),
        ("caught_failures", "failures"),
        ("time_run_ms", "time_total_ms"),
    )
    totals = {pair: {fraction: [0, 0] for fraction in fractions} for pair in pairs}
    for result in results:
        points = result["shadow"]
        cells = []
        for part, whole in pairs:
            for point in points:
                total = totals[(part, whole)][point["fraction"]]
                total[0] += point[part]
                total[1] += point[whole]
            cells.append(" / ".join(_share(point[part], point[whole]) for point in points))
        lines.append(
            f"| {result['project']} | {result['jobs']['evaluated']} | "
            f"{result['jobs']['evaluated_failing']} | " + " | ".join(cells) + " |"
        )
    if results:
        cells = [
            " / ".join(_share(part, whole) for part, whole in totals[pair].values())
            for pair in pairs
        ]
        lines.append(
            f"| **All projects** | {sum(r['jobs']['evaluated'] for r in results)} | "
            f"{sum(r['jobs']['evaluated_failing'] for r in results)} | " + " | ".join(cells) + " |"
        )

    compared = [result for result in results if result["apfd"]["jobs"]]
    lines += [
        "",
        "## Mean APFD against the dataset authors' schedules",
        "",
        "On the failing jobs their schedules cover, the same jobs for every schedule of a project. "
        "optimal-failure is ordered in hindsight: an upper bound, not a competitor.",
        "",
        "| Project | Jobs | " + " | ".join(SCHEDULES) + " |",
        "|---|---:|" + "---:|" * len(SCHEDULES),
    ]
    for result in compared:
        means = result["apfd"]["mean"]
        lines.append(
            f"| {result['project']} | {result['apfd']['jobs']} | "
            + " | ".join(f"{means[name]:.3f}" if name in means else "-" for name in SCHEDULES)
            + " |"
        )
    if compared:
        jobs = sum(result["apfd"]["jobs"] for result in compared)
        weighted = []
        for name in SCHEDULES:
            covered = [r for r in compared if name in r["apfd"]["mean"]]
            if sum(r["apfd"]["jobs"] for r in covered) == jobs:
                total = sum(r["apfd"]["mean"][name] * r["apfd"]["jobs"] for r in covered)
                weighted.append(f"{total / jobs:.3f}")
            else:
                weighted.append("-")
        lines.append(f"| **All jobs** | {jobs} | " + " | ".join(weighted) + " |")
        lines.append("")
        for name in STRATEGIES:
            if name == "optimal-failure":
                continue
            covered = [r["apfd"]["mean"] for r in compared if name in r["apfd"]["mean"]]
            ahead = sum(1 for means in covered if means["testhunch"] > means[name])
            lines.append(f"- testhunch is ahead of {name} on {ahead} of {len(covered)} projects.")
    without = [result["project"] for result in results if not result["apfd"]["jobs"]]
    if without:
        lines += ["", "Without any schedule to compare with: " + ", ".join(without) + "."]
    return "\n".join(lines) + "\n"


def _share(part: int, whole: int) -> str:
    return f"{100 * part / whole:.0f}%" if whole else "-"
