"""Measure LRTS once, under docs/adr/0033.

    uv run python -m benchmarks.lrts --archive ML_TCSP.zip --held-out

Every project of this dataset is held out, so there is no form of this command that does not write
a ledger row (docs/adr/0016). The archive is not in this repository and never will be: it carries
no licence of its own, so its path has to be given.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from benchmarks.heldout import NotFrozen, record_peek
from benchmarks.lrts.data import Archive
from benchmarks.lrts.engine import rankings, replay
from benchmarks.lrts.report import GUARDRAIL, PRIMARY, mean_of_projects, project_mean, verdict
from testhunch import __version__

DEFAULT_OUT = Path("benchmarks") / "results" / "lrts"
BASELINE = "latest-failure"
RANDOM = "random"
SHIPPED = "latest-failure+time^1.0+test_file_changed*0.5"


def markdown(results: Sequence[dict[str, Any]], names: Sequence[str]) -> str:
    projects = [result["project"] for result in results]
    builds = sum(result["builds"]["total"] for result in results)
    suite_runs = sum(result["builds"]["suite_runs"] for result in results)
    evaluated = sum(result["counts"].get("jobs_evaluated", 0) for result in results)
    slice_size = sum(
        sum(1 for flag in result["trials"]["first_failure"] if flag is True) for result in results
    )
    lines = [
        "# LRTS: measured once, under a rule written first",
        "",
        "Cheng, Wang, Jabbarvand and Marinov, *Revisiting Test-Case Prioritization on Long-Running",
        "Test Suites*, ISSTA 2024. Generated by `python -m benchmarks.lrts`; the protocol, fixed",
        "before a single score was computed on this dataset, is docs/adr/0033.",
        "",
        f"{len(projects)} projects, {builds} builds, {suite_runs} suite runs, "
        f"{evaluated} failing trials scored, {slice_size} of them on the first-failure slice.",
        "",
        "**A build's history is the builds that finished before it started.** These suites run for",
        "hours and most builds overlap another, so ordering by timestamp alone would let a build",
        "read results that did not exist when it was scheduled.",
        "",
        "**Every measure is a mean per project, then a mean of those.** Kafka holds two thirds",
        "of the rows of this dataset: pooling trials would publish a result about Kafka under",
        "the name of ten projects. Intervals are 95% percentile bootstrap, resampling projects",
        "and then pull requests inside each project: builds of one pull request are not",
        "independent observations.",
        "",
        "## Primary measure, APFDc with a job's failures as one fault",
        "",
        "| Ranking | " + " | ".join(projects) + " | mean |",
        "|---" * (len(projects) + 2) + "|",
    ]
    for name in names:
        cells = []
        for result in results:
            value = project_mean(result, name, PRIMARY)
            cells.append("n/a" if value is None else f"{value:.3f}")
        overall = mean_of_projects(results, name, PRIMARY)
        mean = "n/a" if overall is None else f"**{overall:.3f}**"
        lines.append(f"| {name} | " + " | ".join(cells) + f" | {mean} |")

    lines += [
        "",
        "## The guardrail: where the failing test had never failed before",
        "",
        "Position of the first failing test, normalized, **lower is better**. The bar is random,",
        "which needs no data to justify and therefore cannot be bent (docs/adr/0018).",
        "",
        "| Ranking | first failure | had failed before |",
        "|---|---:|---:|",
    ]
    for name in names:
        first = mean_of_projects(results, name, GUARDRAIL, first_failure=True)
        rest = mean_of_projects(results, name, GUARDRAIL, first_failure=False)
        lines.append(
            f"| {name} | {'n/a' if first is None else f'{first:.3f}'} "
            f"| {'n/a' if rest is None else f'{rest:.3f}'} |"
        )

    lines += [
        "",
        "## The arbitration",
        "",
        "A candidate ships when it clears the guardrail **and** stays above the baseline it was",
        "built to beat. Neither condition is a number anyone chose: the bar is random, and the",
        "bound is `latest-failure`'s own row in the table above (docs/adr/0033).",
        "",
        "| Candidate | vs random on the slice | vs `latest-failure` on the primary | ships |",
        "|---|---|---|---|",
    ]
    for name in names:
        if name in (BASELINE, RANDOM):
            continue
        outcome = verdict(results, name)
        lines.append(
            f"| {name} | {_interval(outcome['guardrail'])} "
            f"| {_interval(outcome['primary'])} | {'yes' if outcome['ships'] else 'no'} |"
        )
    lines += [
        "",
        "A candidate that ships out of this table has earned a proposal and not a release: it",
        "would still have to be exported as data the package can read, and replayed on RTPTorrent",
        "so that two datasets are on the record rather than one.",
        "",
    ]
    return "\n".join(lines)


def _interval(outcome: dict[str, Any]) -> str:
    if outcome["interval"] is None:
        return "n/a"
    low, high = outcome["interval"]
    return f"{outcome['mean']:+.3f} [{low:+.3f}, {high:+.3f}]"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m benchmarks.lrts")
    parser.add_argument("projects", nargs="*", help="default: every project of the dataset")
    parser.add_argument(
        "--archive",
        type=Path,
        help="the distributed ML_TCSP.zip, read in place and never copied into this repository",
    )
    parser.add_argument(
        "--held-out",
        action="store_true",
        help="required: every project of this dataset is held out and replaying one is recorded",
    )
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument(
        "--from-cache",
        action="store_true",
        help="rebuild the page from the results already under --out, replaying nothing. No replay "
        "produces no number, so there is no look to record (docs/adr/0016)",
    )
    args = parser.parse_args(argv)

    # Checked before the rankings are built, since building them loads a fitted model: a command
    # that is going to be refused should be refused for the reason the user can act on.
    if args.from_cache:
        args.out.mkdir(parents=True, exist_ok=True)
        stored = sorted(args.out.glob("*.json"))
        if not stored:
            parser.error(f"no stored result under {args.out} to rebuild the page from")
        results = [json.loads(path.read_text(encoding="utf-8")) for path in stored]
        names = [ranking.name for ranking in rankings()]
        (args.out / "README.md").write_bytes(markdown(results, names).encode("utf-8"))
        return 0

    if not args.archive:
        parser.error("--archive is required: the dataset is not in this repository")
    if not args.held_out:
        parser.error("every project of LRTS is held out (docs/adr/0013): pass --held-out")
    args.out.mkdir(parents=True, exist_ok=True)
    names = [ranking.name for ranking in rankings()]

    with Archive(args.archive) as archive:
        projects = args.projects or archive.projects()
        unknown = sorted(set(projects) - set(archive.projects()))
        if unknown:
            parser.error(f"not in the archive: {', '.join(unknown)}")
        try:
            # Written before the replay, from a frozen commit, so the look cannot be hidden.
            record_peek("benchmarks.lrts", projects, ", ".join(names), __version__)
        except NotFrozen as exc:
            parser.error(str(exc))

        for project in projects:
            result = replay(archive, project, rankings())
            (args.out / f"{project}.json").write_text(
                json.dumps(result, indent=2) + "\n", encoding="utf-8"
            )
            counts = result["counts"]
            print(
                f"{project}: {result['builds']['total']} builds, "
                f"{counts.get('jobs_evaluated', 0)} trials scored",
                flush=True,
            )

    results = [
        json.loads(path.read_text(encoding="utf-8")) for path in sorted(args.out.glob("*.json"))
    ]
    (args.out / "README.md").write_bytes(markdown(results, names).encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
